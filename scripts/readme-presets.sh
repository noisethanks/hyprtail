#!/bin/sh
# Prints README.md with the block between <!-- presets:start --> and
# <!-- presets:end --> regenerated: one entry per hyprtail/presets/*.conf,
# from its description = line, with a nested bullet for each comment line
# "# variant: <params string> | <short description>" in that file
# (tests/unit/unit.cpp checks each params string against its preset). Run through `make readme-presets` (writes
# README.md) or `make check-readme` (fails if README.md is stale).
#
# Order is the built-in table's: src/Manifest.cpp keys a std::map by file
# stem, so builtinNames() is sorted bytewise, the same as a C-locale glob
# (make test-unit checks that the table and hyprtail/presets/ match).
# Anything hand-written goes outside the markers; the block is replaced whole.
set -eu
export LC_ALL=C
readme=../README.md
start='<!-- presets:start -->'
end='<!-- presets:end -->'

if [ "$(grep -cxF "$start" "$readme")" != 1 ] || [ "$(grep -cxF "$end" "$readme")" != 1 ] ||
    [ "$(grep -nxF "$start" "$readme" | cut -d: -f1)" -ge "$(grep -nxF "$end" "$readme" | cut -d: -f1)" ]; then
    echo "error: $readme needs exactly one '$start' line followed by one '$end' line" >&2
    exit 1
fi

sed "/^$start\$/q" "$readme"
echo '<!-- Generated by `make readme-presets` from each preset'"'"'s description = and # variant: lines; do not edit. -->'
for conf in hyprtail/presets/*.conf; do
    name=$(basename "$conf" .conf)
    # Manifest grammar (src/Manifest.hpp): '#' starts a comment, values are trimmed.
    desc=$(sed -n 's/#.*//; s/^[[:space:]]*description[[:space:]]*=[[:space:]]*//p' "$conf" | sed 's/[[:space:]]*$//')
    if [ -z "$desc" ]; then
        echo "error: $conf has no description = line" >&2
        exit 1
    fi
    printf -- '- **`builtin:%s`**: %s\n' "$name" "$desc"
    variants=$(sed -n 's/^#[[:space:]]*variant:[[:space:]]*//p' "$conf")
    [ -n "$variants" ] || continue
    while IFS= read -r v; do
        params=$(printf '%s' "${v%%|*}" | sed 's/[[:space:]]*$//')
        what=$(printf '%s' "${v#*|}" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')
        case $v in *'|'*) ;; *) what= ;; esac
        if [ -z "$params" ] || [ -z "$what" ]; then
            echo "error: $conf: variant line needs '<params string> | <short description>': $v" >&2
            exit 1
        fi
        printf -- '  - %s: `%s`\n' "$what" "$params"
    done <<VARIANTS
$variants
VARIANTS
done
sed -n "/^$end\$/,\$p" "$readme"
